const ATTRS = {
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-miterlimit': 'strokeMiterlimit',
  'stroke-dasharray': 'strokeDasharray',
  'fill-rule': 'fillRule',
  'clip-rule': 'clipRule',
  'fill-opacity': 'fillOpacity',
  'stroke-opacity': 'strokeOpacity',
  'stop-color': 'stopColor',
  'stop-opacity': 'stopOpacity',
  'xlink:href': 'href',
}

function convert(file, keepColors) {
  const svg = readFileSync(join(svgDir, `${file}.svg`), 'utf8')
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1]
  let body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    // Figma wraps icons in bounding-box clips/masks; dropping them avoids duplicate DOM ids.
    .replace(/<defs>\s*<clipPath[\s\S]*?<\/clipPath>\s*<\/defs>/g, '')
    .replace(/<mask[\s\S]*?<\/mask>/g, '')
    .replace(/ (clip-path|mask)="url\(#[^)]+\)"/g, '')
  for (const [from, to] of Object.entries(ATTRS)) body = body.replaceAll(`${from}=`, `${to}=`)
  if (!keepColors) body = body.replace(/(fill|stroke)="#[0-9A-Fa-f]{3,8}"/g, '$1="currentColor"')
  return { viewBox, body: body.trim().replace(/\n/g, '\n      ') }
}

const components = ICONS.map(([name, file, keepColors]) => {
  const { viewBox, body } = convert(file, keepColors)
  return `export function ${name}(props: IconProps) {
  return (
    <svg viewBox="${viewBox}" fill="none" aria-hidden="true" focusable="false" {...props}>
      ${body}
    </svg>
  )
}`
})

writeFileSync(
  out,
  `// Generated by scripts/figma/build-icons.mjs from the Figma exports. Do not edit by hand.
import type { SVGProps } from 'react'

type IconProps = SVGProps<SVGSVGElement>

${components.join('\n\n')}
`,
)
console.log(`✔ ${ICONS.length} icons → src/shared/components/icons.tsx`)
