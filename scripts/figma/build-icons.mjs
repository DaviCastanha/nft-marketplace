#!/usr/bin/env node
// Generates src/shared/components/icons.tsx from the SVGs exported from Figma
// (design/assets/svg, local only). Monochrome icons switch to currentColor.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const svgDir = join(root, 'design', 'assets', 'svg')
const out = join(root, 'src', 'shared', 'components', 'icons.tsx')

